using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Caly.Core.Models;

namespace Caly.Core.Services;

/// <summary>
/// Builds story map (GeoStory) configuration by reverse-mapping verified geocoded
/// locations back to Popo tree nodes via shared source_block_id UUIDs.
///
/// The Popo tree hierarchy is not blindly trusted; instead, chapter candidates are
/// scored by location density and content depth, and ancestor/descendant conflicts
/// are resolved in favor of the most granular node that still has sufficient data.
/// </summary>
public class GeoStoryBuilder
{
    // Minimum number of matched geocoded locations for a node to qualify as a chapter.
    const int MinLocations = 1;

    // Minimum number of source content blocks for a node to qualify as a chapter.
    // Lowered to 1 to allow more granular chapters (single location with meaningful title).
    const int MinContentBlocks = 1;

    // When a child node has at least this fraction of its parent's locations,
    // the child is preferred over the parent (more granular).
    // Only used when the child has fewer than MinIndependentLocations.
    const double ChildLocationRatio = 0.7;

    // A child with at least this many locations is considered independently
    // viable regardless of how many locations its parent has.
    const int MinIndependentLocations = 3;

    // All known layer IDs (matching the layers generated by GeoJsonService).
    static readonly string[] AllLayerIds = new[]
    {
        "layer-adverbial",
        "layer-subject",
        "layer-object",
        "layer-attributive",
        "layer-predicative",
        "layer-unknown"
    };

    /// <summary>
    /// Parsed representation of a single geocoded location feature
    /// from the geolibre.json layers.
    /// </summary>
    public class GeoFeature
    {
        public string Name { get; set; } = "";
        public double Longitude { get; set; }
        public double Latitude { get; set; }
        public string SyntacticRole { get; set; } = "Unknown";
        public string SpatialRole { get; set; } = "";
        public string VerbSpatialClass { get; set; } = "";
        public List<string> SourceBlockIds { get; set; } = new();
        public string SourceBlockContent { get; set; } = "";

        // OSM spatial metadata for camera enhancement
        public double? BboxMinLat { get; set; }
        public double? BboxMaxLat { get; set; }
        public double? BboxMinLon { get; set; }
        public double? BboxMaxLon { get; set; }
        public string OsmCategory { get; set; } = "";
        public string OsmType { get; set; } = "";
        public int PlaceRank { get; set; }  // Nominatim place_rank: 3-4=国家, 5-9=省, 10-12=县, 13-16=城市, 17-21=区/镇, 22+=街道
    }

    /// <summary>
    /// Intermediate candidate during tree walk.
    /// </summary>
    class ChapterCandidate
    {
        public AnalysisTreeNode TreeNode { get; set; } = null!;
        public string Title { get; set; } = "";
        public int TreeOrder { get; set; }
        public int Depth { get; set; }
        public List<GeoFeature> Locations { get; set; } = new();
        public int ContentBlockCount { get; set; }
        public HashSet<string> AllUuids { get; set; } = new();
    }

    /// <summary>
    /// Build story map configuration from Popo tree and verified geocoded features.
    /// </summary>
    /// <param name="popoRoot">Root node of the Popo document tree.</param>
    /// <param name="features">GeoFeature list extracted from geocoding results.</param>
    /// <param name="documentTitle">Document name used as the story title (fallback).</param>
    /// <param name="nlpService">Optional NLP service for generating title from chapter titles.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>GeoStoryConfig ready to embed in geolibre.json, or null if no valid chapters.</returns>
    public async Task<GeoStoryConfig?> BuildAsync(
        AnalysisTreeNode? popoRoot,
        List<GeoFeature> features,
        string documentTitle,
        SemanticAnalysisService? nlpService = null,
        CancellationToken cancellationToken = default)
    {
        if (popoRoot is null || features.Count == 0)
            return null;

        // 1. Build UUID \u2192 GeoFeature index for O(1) lookup
        var uuidToFeature = new Dictionary<string, GeoFeature>();
        foreach (var feature in features)
        {
            foreach (var uuid in feature.SourceBlockIds)
            {
                if (!uuidToFeature.ContainsKey(uuid))
                    uuidToFeature[uuid] = feature;
            }
        }

        // 2. Walk the Popo tree and collect chapter candidates
        var candidates = new List<ChapterCandidate>();
        int order = 0;
        WalkPopoTree(popoRoot, uuidToFeature, candidates, ref order, 0);

        // 3. Filter: must have enough locations AND content blocks
        var valid = candidates
            .Where(c => c.Locations.Count >= MinLocations
                     && c.ContentBlockCount >= MinContentBlocks)
            .ToList();

        if (valid.Count == 0)
            return null;

        // 4. Resolve ancestor/descendant conflicts
        var selected = ResolveAncestorConflicts(valid);

        // 5. Sort by original tree traversal order
        selected = selected.OrderBy(c => c.TreeOrder).ToList();

        // 6. Build final chapters
        var chapters = new List<GeoChapter>();
        for (int i = 0; i < selected.Count; i++)
        {
            chapters.Add(BuildChapter(selected[i], i));
        }

        // 7. Generate story title using NLP /analyze/title API
        //    Data source: first few chapter titles (limited to avoid overly long input)
        string storyTitle = documentTitle;
        if (nlpService is not null && chapters.Count > 0)
        {
            // Use only the first 5 chapter titles to keep input concise
            var titlesToUse = chapters.Take(5).Select(c => c.Title);
            var chapterTitlesText = string.Join("\uff0c", titlesToUse);
            System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Generating title from chapter titles: \"{chapterTitlesText}\"");
            try
            {
                var generatedTitle = await nlpService.GenerateTitleAsync(
                    chapterTitlesText,
                    targetChars: 20,
                    cancellationToken: cancellationToken);
                if (!string.IsNullOrEmpty(generatedTitle))
                {
                    storyTitle = generatedTitle;
                    System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Using NLP-generated title: \"{storyTitle}\"");
                }
                else
                {
                    System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] NLP returned null, using fallback title: \"{storyTitle}\"");
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Title generation failed, using fallback: {ex.Message}");
            }
        }
        else
        {
            if (nlpService is null)
                System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] nlpService is null, using fallback title: \"{storyTitle}\"");
            else
                System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] No chapters ({chapters.Count}), using fallback title: \"{storyTitle}\"");
        }

        return new GeoStoryConfig
        {
            Title = storyTitle,
            Theme = "light",
            ShowMarkers = true,
            Chapters = chapters
        };
    }

    /// <summary>
    /// Synchronous wrapper for BuildAsync (for backward compatibility).
    /// </summary>
    public GeoStoryConfig? Build(
        AnalysisTreeNode? popoRoot,
        List<GeoFeature> features,
        string documentTitle)
    {
        return BuildAsync(popoRoot, features, documentTitle, null, CancellationToken.None).GetAwaiter().GetResult();
    }


    /// <summary>
    /// Depth-first walk of the Popo tree, collecting candidates at every node
    /// that has a meaningful title.
    /// </summary>
    void WalkPopoTree(
        AnalysisTreeNode node,
        Dictionary<string, GeoFeature> uuidToFeature,
        List<ChapterCandidate> candidates,
        ref int order,
        int depth)
    {
        // Collect all source_block_ids throughout this subtree
        var allUuids = CollectAllSourceBlockIds(node);

        // Match geocoded locations
        var matchedLocations = allUuids
            .Where(uuidToFeature.ContainsKey)
            .Select(uuid => uuidToFeature[uuid])
            .DistinctBy(f => f.Name)
            .ToList();

        // Register as candidate if the node has a meaningful title
        if (!string.IsNullOrEmpty(node.Title)
            && node.Title != "Default Title"
            && node.Title.Trim().Length > 1)
        {
            candidates.Add(new ChapterCandidate
            {
                TreeNode = node,
                Title = node.Title,
                TreeOrder = order++,
                Depth = depth,
                Locations = matchedLocations,
                ContentBlockCount = allUuids.Count,
                AllUuids = allUuids
            });
        }

        // Recurse into children
        foreach (var child in node.Children)
        {
            WalkPopoTree(child, uuidToFeature, candidates, ref order, depth + 1);
        }
    }

    /// <summary>
    /// Recursively collects all source_block_ids from a node and its descendants.
    /// </summary>
    static HashSet<string> CollectAllSourceBlockIds(AnalysisTreeNode node)
    {
        var ids = new HashSet<string>(node.SourceBlockIds ?? Enumerable.Empty<string>());
        if (node.Children is not null)
        {
            foreach (var child in node.Children)
            {
                ids.UnionWith(CollectAllSourceBlockIds(child));
            }
        }
        return ids;
    }

    /// <summary>
    /// Resolves ancestor/descendant conflicts: when both a parent and its child
    /// qualify as chapters, prefer the child if it has enough locations relative
    /// to the parent (>= 70%). Otherwise keep the parent.
    /// </summary>
    static List<ChapterCandidate> ResolveAncestorConflicts(List<ChapterCandidate> candidates)
    {
        var toRemove = new HashSet<ChapterCandidate>();

        // Process deeper nodes first
        var sorted = candidates.OrderByDescending(c => c.Depth).ToList();

        for (int i = 0; i < sorted.Count; i++)
        {
            if (toRemove.Contains(sorted[i]))
                continue;

            for (int j = i + 1; j < sorted.Count; j++)
            {
                if (toRemove.Contains(sorted[j]))
                    continue;

                var deeper = sorted[i];
                var shallower = sorted[j];

                // Check ancestor relationship: shallower's UUIDs contain deeper's
                if (shallower.AllUuids.IsSupersetOf(deeper.AllUuids)
                    && shallower.AllUuids.Count > deeper.AllUuids.Count)
                {
                    // Child is independently viable → always prefer child
                    // Child has enough of the parent's locations → prefer child
                    // Otherwise keep the parent
                    if (deeper.Locations.Count >= MinIndependentLocations
                        || deeper.Locations.Count >= shallower.Locations.Count * ChildLocationRatio)
                        toRemove.Add(shallower);
                    else
                        toRemove.Add(deeper);
                }
            }
        }

        return candidates.Where(c => !toRemove.Contains(c)).ToList();
    }

    /// <summary>
    /// Builds a single GeoChapter from a validated candidate.
    /// Camera behavior adapts to spatial_role and verb_spatial_class.
    /// </summary>
    static GeoChapter BuildChapter(ChapterCandidate candidate, int index)
    {
        var locs = candidate.Locations;
        var (lng, lat, zoom, pitch, bearing, mapAnimation) = CalculateSpatialCamera(locs);

        // Determine which layers are "active" in this chapter
        var activeLayerIds = locs
            .Select(l => RoleToLayerId(l.SyntacticRole))
            .Distinct()
            .ToHashSet();

        // Description: use the first location's source text, truncated
        var description = locs.FirstOrDefault()?.SourceBlockContent ?? "";
        if (description.Length > 200)
            description = description.Substring(0, 200) + "...";

        return new GeoChapter
        {
            Id = $"chapter-{index}",
            Title = candidate.Title,
            Description = description,
            Alignment = index % 2 == 0 ? "right" : "left",
            MapAnimation = mapAnimation,
            Lng = lng,
            Lat = lat,
            Zoom = zoom,
            Pitch = pitch,
            Bearing = bearing,
            // onChapterEnter: highlight active layers, dim the rest
            OnChapterEnter = AllLayerIds.Select(id => new GeoLayerEffect
            {
                LayerId = id,
                Opacity = activeLayerIds.Contains(id) ? 1.0 : 0.2,
                Duration = 500
            }).ToList(),
            // onChapterExit: restore all layers to default
            OnChapterExit = AllLayerIds.Select(id => new GeoLayerEffect
            {
                LayerId = id,
                Opacity = 0.7,
                Duration = 300
            }).ToList(),

            Beats = BuildBeats(locs)
        };
    }

    /// <summary>
    /// Builds narrative beats from locations that have meaningful spatial roles.
    /// Excludes MODIFIER and STATIC — only dynamic spatial roles generate beats.
    /// </summary>
    static List<GeoBeat> BuildBeats(List<GeoFeature> locations)
    {
        var beatRoles = new HashSet<string> { "CONTAINER", "TARGET", "ORIGIN", "PATH", "ACTOR" };

        return locations
            .Where(l => !string.IsNullOrEmpty(l.SpatialRole)
                     && beatRoles.Contains(l.SpatialRole))
            .Select(l => new GeoBeat
            {
                LocationName = l.Name,
                SpatialRole = l.SpatialRole!,
                Verb = l.VerbSpatialClass ?? "",
                Lng = l.Longitude,
                Lat = l.Latitude,
                // Use place_rank as base zoom, then adjust by spatial role
                Zoom = Math.Clamp(
                    GetZoomFromPlaceRank(l.PlaceRank)
                    + (l.SpatialRole == "TARGET" ? 2 : 0)
                    + (l.SpatialRole == "ACTOR" ? 1 : 0),
                    3, 20),
                Pitch = l.SpatialRole switch
                {
                    "PATH" => 35,
                    "ACTOR" => 20,
                    "CONTAINER" => 10,
                    _ => 0
                },
                Bearing = 0
            })
            .ToList();
    }

    /// <summary>
    /// Calculates camera position, zoom, pitch, bearing, and animation type
    /// based on the spatial roles and verb spatial classes of the chapter's locations.
    /// </summary>
    static (double Lng, double Lat, double Zoom, double Pitch, double Bearing, string MapAnimation)
        CalculateSpatialCamera(List<GeoFeature> locations)
    {
        if (locations.Count == 0)
            return (0, 0, 3, 0, 0, "flyTo");

        // Determine the dominant spatial role (highest priority first)
        var rolePriority = new Dictionary<string, int>
        {
            { "PATH", 6 }, { "TARGET", 5 }, { "ORIGIN", 4 },
            { "ACTOR", 3 }, { "CONTAINER", 2 }, { "MODIFIER", 1 }
        };

        var dominantRole = locations
            .Where(l => !string.IsNullOrEmpty(l.SpatialRole))
            .OrderByDescending(l => rolePriority.GetValueOrDefault(l.SpatialRole!, 0))
            .Select(l => l.SpatialRole)
            .FirstOrDefault() ?? "STATIC";

        // Base camera from bounding box
        var (centerLng, centerLat, baseZoom) = ComputeBaseCamera(locations);

        // Apply spatial role adjustments
        double zoom = baseZoom;
        double pitch = 0;
        double bearing = 0;
        string mapAnimation = "flyTo";

        switch (dominantRole)
        {
            case "PATH":
                zoom = baseZoom;
                pitch = 35;
                bearing = ComputePathBearing(locations);
                mapAnimation = "flyTo";
                break;

            case "TARGET":
                zoom = Math.Min(baseZoom + 2, 18);
                pitch = 0;
                mapAnimation = "easeTo";
                break;

            case "ORIGIN":
                zoom = baseZoom;
                pitch = 0;
                mapAnimation = "flyTo";
                break;

            case "ACTOR":
                zoom = Math.Min(baseZoom + 1, 18);
                pitch = 20;
                mapAnimation = "flyTo";
                break;

            case "CONTAINER":
                zoom = baseZoom;
                pitch = 10;
                mapAnimation = "flyTo";
                break;

            case "MODIFIER":
                zoom = Math.Max(baseZoom - 1, 2);
                pitch = 0;
                mapAnimation = "flyTo";
                break;

            default: // STATIC or unknown
                zoom = baseZoom;
                pitch = 0;
                mapAnimation = "flyTo";
                break;
        }

        // Verb class overrides for animation type
        var dominantVerbClass = locations
            .Where(l => !string.IsNullOrEmpty(l.VerbSpatialClass))
            .Select(l => l.VerbSpatialClass)
            .FirstOrDefault();

        if (dominantVerbClass == "MOVE_TO")
            mapAnimation = "easeTo";
        else if (dominantVerbClass == "VIEW")
            pitch = Math.Max(pitch, 15);

        return (centerLng, centerLat, zoom, pitch, bearing, mapAnimation);
    }

    /// <summary>
    /// Computes base camera from bounding box of all locations.
    /// </summary>
    static (double Lng, double Lat, double Zoom) ComputeBaseCamera(List<GeoFeature> locations)
    {
        if (locations.Count == 1)
        {
            var loc = locations[0];
            // Use place_rank to determine appropriate zoom level
            double locZoom = GetZoomFromPlaceRank(loc.PlaceRank);
            return (loc.Longitude, loc.Latitude, locZoom);
        }

        var lngs = locations.Select(l => l.Longitude).ToList();
        var lats = locations.Select(l => l.Latitude).ToList();
        var centerLng = (lngs.Min() + lngs.Max()) / 2;
        var centerLat = (lats.Min() + lats.Max()) / 2;

        var lonSpan = lngs.Max() - lngs.Min();
        var latSpan = lats.Max() - lats.Min();
        var maxSpan = Math.Max(lonSpan, latSpan);

        if (maxSpan < 0.0001)
        {
            // All points are the same, use place_rank of the first location
            double rankZoom = GetZoomFromPlaceRank(locations[0].PlaceRank);
            return (centerLng, centerLat, rankZoom);
        }

        var zoom = Math.Log(360.0 / maxSpan) / Math.Log(2.0) - 0.5;
        zoom = Math.Max(1.0, Math.Min(20.0, zoom));

        return (centerLng, centerLat, zoom);
    }

    /// <summary>
    /// Converts Nominatim place_rank to an appropriate map zoom level.
    /// place_rank ranges: 3-4=国家, 5-9=省/州, 10-12=县, 13-16=城市, 17-21=区/镇, 22-24=社区, 25-27=街道, 28+=建筑
    /// </summary>
    static double GetZoomFromPlaceRank(int placeRank)
    {
        if (placeRank <= 0)
            return 12; // Default zoom when place_rank is not available

        return placeRank switch
        {
            <= 2  => 3,    // Continent/Sea
            <= 4  => 5,    // Country
            <= 6  => 7,    // State/province (high level)
            <= 9  => 8,    // State/province
            <= 12 => 10,   // County
            <= 16 => 12,   // City
            <= 21 => 14,   // District/town
            <= 24 => 16,   // Locality/community
            <= 27 => 17,   // Street
            _     => 18    // Building/house
        };
    }

    /// <summary>
    /// Computes bearing angle from PATH-type locations' OSM bounding boxes.
    /// Falls back to 0 (north-up) if no bbox data is available.
    /// </summary>
    static double ComputePathBearing(List<GeoFeature> locations)
    {
        var pathLocs = locations
            .Where(l => l.SpatialRole == "PATH" && l.BboxMinLat.HasValue)
            .ToList();

        if (pathLocs.Count == 0)
            pathLocs = locations.Where(l => l.BboxMinLat.HasValue).ToList();

        if (pathLocs.Count == 0)
            return 0;

        // Use the first location with bbox data to determine path direction
        var loc = pathLocs[0];
        var dLon = (loc.BboxMaxLon!.Value - loc.BboxMinLon!.Value);
        var dLat = (loc.BboxMaxLat!.Value - loc.BboxMinLat!.Value);

        // atan2(dLon, dLat) → radians → degrees, normalized to [0, 360)
        var bearingRad = Math.Atan2(dLon, dLat);
        var bearingDeg = bearingRad * 180.0 / Math.PI;
        if (bearingDeg < 0) bearingDeg += 360;

        return bearingDeg;
    }

    /// <summary>
    /// Maps a syntactic role string to the corresponding GeoLibre layer ID.
    /// </summary>
    static string RoleToLayerId(string role) => role switch
    {
        "Adverbial" => "layer-adverbial",
        "Subject" => "layer-subject",
        "Object" => "layer-object",
        "Attributive" => "layer-attributive",
        "Predicative" => "layer-predicative",
        _ => "layer-unknown"
    };

    /// <summary>
    /// Converts a GeoStoryConfig tree to Dictionary<string, object> for
    /// AOT-safe JSON serialization via GeoJsonService.BuildJson().
    /// Uses GeoLibre 0.2.0 format with nested "location" object per chapter.
    /// </summary>
    public static Dictionary<string, object>? GeoStoryConfigToDict(GeoStoryConfig? config)
    {
        if (config is null)
            return null;

        var dict = new Dictionary<string, object>
        {
            { "title", config.Title },
            { "subtitle", config.Subtitle },
            { "byline", config.Byline },
            { "footer", config.Footer },
            { "theme", config.Theme },
            { "showMarkers", config.ShowMarkers },
            { "markerColor", config.MarkerColor },
            { "inset", config.Inset },
            { "insetPosition", config.InsetPosition },
            { "hideChapterNav", config.HideChapterNav },
            { "startSlide", config.StartSlide },
            { "endSlide", config.EndSlide }
        };

        if (config.Chapters.Count > 0)
        {
            var chapterDicts = new List<Dictionary<string, object>>();
            foreach (var ch in config.Chapters)
            {
                chapterDicts.Add(ChapterToDict(ch));
            }
            dict["chapters"] = chapterDicts;
        }
        else
        {
            dict["chapters"] = Array.Empty<object>();
        }

        return dict;
    }

    static Dictionary<string, object> ChapterToDict(GeoChapter chapter)
    {
        // GeoLibre 0.2.0 uses a nested "location" object for camera parameters
        var location = new Dictionary<string, object>
        {
            { "center", new[] { chapter.Lng, chapter.Lat } },
            { "zoom", chapter.Zoom },
            { "pitch", chapter.Pitch },
            { "bearing", chapter.Bearing }
        };

        var dict = new Dictionary<string, object>
        {
            { "id", chapter.Id },
            { "title", chapter.Title },
            { "description", chapter.Description },
            { "image", chapter.Image },
            { "alignment", chapter.Alignment },
            { "hidden", chapter.Hidden },
            { "location", location },
            { "mapAnimation", chapter.MapAnimation },
            { "rotateAnimation", chapter.RotateAnimation }
        };

        if (chapter.OnChapterEnter.Count > 0)
            dict["onChapterEnter"] = LayerEffectsToArray(chapter.OnChapterEnter);
        else
            dict["onChapterEnter"] = Array.Empty<object>();

        if (chapter.OnChapterExit.Count > 0)
            dict["onChapterExit"] = LayerEffectsToArray(chapter.OnChapterExit);
        else
            dict["onChapterExit"] = Array.Empty<object>();

        if (chapter.Beats.Count > 0)
            dict["beats"] = BeatsToArray(chapter.Beats);
        else
            dict["beats"] = Array.Empty<object>();

        return dict;
    }

    static object[] LayerEffectsToArray(List<GeoLayerEffect> effects)
    {
        return effects.Select(e => (object)new Dictionary<string, object>
        {
            { "layerId", e.LayerId },
            { "opacity", e.Opacity },
            { "duration", e.Duration }
        }).ToArray();
    }

    static object[] BeatsToArray(List<GeoBeat> beats)
    {
        return beats.Select(b => (object)new Dictionary<string, object>
        {
            { "locationName", b.LocationName },
            { "spatialRole", b.SpatialRole },
            { "verb", b.Verb },
            { "lng", b.Lng },
            { "lat", b.Lat },
            { "zoom", b.Zoom },
            { "pitch", b.Pitch },
            { "bearing", b.Bearing }
        }).ToArray();
    }
}
