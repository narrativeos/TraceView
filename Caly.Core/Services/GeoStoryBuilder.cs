using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Caly.Core.Models;

namespace Caly.Core.Services;

/// <summary>
/// Builds story map (GeoStory) configuration by reverse-mapping verified geocoded
/// locations back to Popo tree nodes via shared source_block_id UUIDs.
///
/// The Popo tree hierarchy is not blindly trusted; instead, chapter candidates are
/// scored by location density and content depth, and ancestor/descendant conflicts
/// are resolved in favor of the most granular node that still has sufficient data.
/// </summary>
public class GeoStoryBuilder
{
    // Minimum number of matched geocoded locations for a node to qualify as a chapter.
    const int MinLocations = 1;

    // Minimum number of source content blocks for a node to qualify as a chapter.
    // Lowered to 1 to allow more granular chapters (single location with meaningful title).
    const int MinContentBlocks = 1;

    // When a child node has at least this fraction of its parent's locations,
    // the child is preferred over the parent (more granular).
    // Only used when the child has fewer than MinIndependentLocations.
    const double ChildLocationRatio = 0.7;

    // A child with at least this many locations is considered independently
    // viable regardless of how many locations its parent has.
    const int MinIndependentLocations = 3;

    // All known layer IDs (matching the layers generated by GeoJsonService).
    static readonly string[] AllLayerIds = new[]
    {
        "layer-adverbial",
        "layer-subject",
        "layer-object",
        "layer-attributive",
        "layer-predicative",
        "layer-unknown"
    };

    /// <summary>
    /// Parsed representation of a single geocoded location feature
    /// from the geolibre.json layers.
    /// </summary>
    public class GeoFeature
    {
        public string Name { get; set; } = "";
        public double Longitude { get; set; }
        public double Latitude { get; set; }
        public string SyntacticRole { get; set; } = "Unknown";
        public string SpatialRole { get; set; } = "";
        public string VerbSpatialClass { get; set; } = "";
        public List<string> SourceBlockIds { get; set; } = new();
        public string SourceBlockContent { get; set; } = "";

        // OSM spatial metadata for camera enhancement
        public double? BboxMinLat { get; set; }
        public double? BboxMaxLat { get; set; }
        public double? BboxMinLon { get; set; }
        public double? BboxMaxLon { get; set; }
        public string OsmCategory { get; set; } = "";
        public string OsmType { get; set; } = "";
        public int PlaceRank { get; set; }  // Nominatim place_rank: 3-4=国家, 5-9=省, 10-12=县, 13-16=城市, 17-21=区/镇, 22+=街道
    }

    /// <summary>
    /// Intermediate candidate during tree walk.
    /// </summary>
    class ChapterCandidate
    {
        public AnalysisTreeNode TreeNode { get; set; } = null!;
        public string Title { get; set; } = "";
        public int TreeOrder { get; set; }
        public int Depth { get; set; }
        public List<GeoFeature> Locations { get; set; } = new();
        public int ContentBlockCount { get; set; }
        public HashSet<string> AllUuids { get; set; } = new();
    }

    /// <summary>
    /// Per-depth camera range constraints derived from global analysis.
    /// Used to keep camera transitions smooth across chapters at the same structural level.
    /// </summary>
    struct DepthCameraRange
    {
        public int Depth;
        public double MinZoom;
        public double MaxZoom;
        public double TypicalZoom;
        public double MinPitch;
        public double MaxPitch;
        public double TypicalPitch;
    }

    /// <summary>
    /// Build story map configuration from Popo tree and verified geocoded features.
    /// </summary>
    /// <param name="popoRoot">Root node of the Popo document tree.</param>
    /// <param name="features">GeoFeature list extracted from geocoding results.</param>
    /// <param name="documentTitle">Document name used as the story title (fallback).</param>
    /// <param name="nlpService">Optional NLP service for generating title from chapter titles.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>GeoStoryConfig ready to embed in geolibre.json, or null if no valid chapters.</returns>
    public async Task<GeoStoryConfig?> BuildAsync(
        AnalysisTreeNode? popoRoot,
        List<GeoFeature> features,
        string documentTitle,
        SemanticAnalysisService? nlpService = null,
        CancellationToken cancellationToken = default)
    {
        if (popoRoot is null || features.Count == 0)
            return null;

        // 1. Build UUID \u2192 GeoFeature index for O(1) lookup
        var uuidToFeature = new Dictionary<string, GeoFeature>();
        foreach (var feature in features)
        {
            foreach (var uuid in feature.SourceBlockIds)
            {
                if (!uuidToFeature.ContainsKey(uuid))
                    uuidToFeature[uuid] = feature;
            }
        }

        // 2. Walk the Popo tree and collect chapter candidates
        var candidates = new List<ChapterCandidate>();
        int order = 0;
        var ancestorStack = new List<ChapterCandidate>();
        WalkPopoTree(popoRoot, uuidToFeature, candidates, ancestorStack, ref order, 0, cancellationToken);

        // 3. Filter: must have enough locations AND content blocks
        var valid = candidates
            .Where(c => c.Locations.Count >= MinLocations
                     && c.ContentBlockCount >= MinContentBlocks)
            .ToList();

        if (valid.Count == 0)
            return null;

        // 4. Sort by original tree traversal order
        var selected = valid.OrderBy(c => c.TreeOrder).ToList();

        // 5. Analyze per-depth camera ranges from all candidates
        var depthRanges = AnalyzeDepthRanges(selected, cancellationToken);
        System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Depth camera ranges:");
        foreach (var dr in depthRanges)
        {
            System.Diagnostics.Debug.WriteLine($"  Depth {dr.Depth}: zoom=[{dr.MinZoom:F1}, {dr.MaxZoom:F1}] pitch=[{dr.MinPitch:F1}, {dr.MaxPitch:F1}]");
        }

        // 6. Build final chapters with depth-based camera constraints & smooth transitions
        // NOTE: Do NOT insert transition chapters here - they will be generated in Phase 3
        // after global optimization to avoid duplicate/nested transitions.
        var chapters = new List<GeoChapter>();
        GeoChapter? previousChapter = null;
        for (int i = 0; i < selected.Count; i++)
        {
            var chapter = BuildChapter(selected[i], i, depthRanges, previousChapter, cancellationToken);
            chapters.Add(chapter);
            previousChapter = chapter;
        }

        // 6.5 Phase 2: Global camera parameter optimization
        // After all chapters are built, do a global pass to smooth zoom/pitch transitions
        OptimizeGlobalCameraParameters(chapters);

        // 6.6 Phase 3: Generate transition chapters after global optimization
        var finalChapters = new List<GeoChapter>();
        GeoChapter? prevChapter = null;
        int finalIndex = 0;
        foreach (var chapter in chapters)
        {
            if (prevChapter is not null)
            {
                var transitions = GenerateTransitionChapters(prevChapter, chapter, finalIndex);
                if (transitions.Count > 0)
                {
                    finalChapters.AddRange(transitions);
                    finalIndex += transitions.Count;
                }
            }
            // Set ID and alignment based on final position (do this AFTER transitions)
            chapter.Id = $"chapter-{finalIndex}";
            chapter.Alignment = finalIndex % 2 == 0 ? "right" : "left";
            finalChapters.Add(chapter);
            finalIndex++;
            prevChapter = chapter;
        }
        chapters = finalChapters;

        // 7. Generate story title using NLP /analyze/title API
        //    Data source: first few chapter titles (limited to avoid overly long input)
        string storyTitle = documentTitle;
        if (nlpService is not null && chapters.Count > 0)
        {
            // Use only the first 5 chapter titles to keep input concise
            var titlesToUse = chapters.Take(5).Select(c => c.Title);
            var chapterTitlesText = string.Join("\uff0c", titlesToUse);
            System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Generating title from chapter titles: \"{chapterTitlesText}\"");
            try
            {
                var generatedTitle = await nlpService.GenerateTitleAsync(
                    chapterTitlesText,
                    targetChars: 20,
                    cancellationToken: cancellationToken);
                if (!string.IsNullOrEmpty(generatedTitle))
                {
                    storyTitle = generatedTitle;
                    System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Using NLP-generated title: \"{storyTitle}\"");
                }
                else
                {
                    System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] NLP returned null, using fallback title: \"{storyTitle}\"");
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] Title generation failed, using fallback: {ex.Message}");
            }
        }
        else
        {
            if (nlpService is null)
                System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] nlpService is null, using fallback title: \"{storyTitle}\"");
            else
                System.Diagnostics.Debug.WriteLine($"[GeoStoryBuilder] No chapters ({chapters.Count}), using fallback title: \"{storyTitle}\"");
        }

        return new GeoStoryConfig
        {
            Title = storyTitle,
            Theme = "light",
            ShowMarkers = true,
            Chapters = chapters
        };
    }

    /// <summary>
    /// Synchronous wrapper for BuildAsync (for backward compatibility).
    /// </summary>
    public GeoStoryConfig? Build(
        AnalysisTreeNode? popoRoot,
        List<GeoFeature> features,
        string documentTitle)
    {
        return BuildAsync(popoRoot, features, documentTitle, null, CancellationToken.None).GetAwaiter().GetResult();
    }


    /// <summary>
    /// Depth-first walk of the Popo tree, collecting candidates at every node
    /// that has a meaningful title.
    /// Conflict resolution is done inline using an ancestor list (O(n*d) instead of O(n²)).
    /// </summary>
    void WalkPopoTree(
        AnalysisTreeNode node,
        Dictionary<string, GeoFeature> uuidToFeature,
        List<ChapterCandidate> candidates,
        List<ChapterCandidate> ancestorStack,
        ref int order,
        int depth,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        // Collect all source_block_ids throughout this subtree
        var allUuids = CollectAllSourceBlockIds(node, cancellationToken);

        // Match geocoded locations
        var matchedLocations = allUuids
            .Where(uuidToFeature.ContainsKey)
            .Select(uuid => uuidToFeature[uuid])
            .DistinctBy(f => f.Name)
            .ToList();

        // Register as candidate if the node has a meaningful title
        if (!string.IsNullOrEmpty(node.Title)
            && node.Title != "Default Title"
            && node.Title.Trim().Length > 1)
        {
            var newCandidate = new ChapterCandidate
            {
                TreeNode = node,
                Title = node.Title,
                TreeOrder = order++,
                Depth = depth,
                Locations = matchedLocations,
                ContentBlockCount = allUuids.Count,
                AllUuids = allUuids
            };

            // Inline conflict resolution: check against all ancestors on the stack
            var ancestorsToRemove = new List<ChapterCandidate>();
            bool shouldAddNewCandidate = true;

            foreach (var ancestor in ancestorStack)
            {
                cancellationToken.ThrowIfCancellationRequested();

                // Check if ancestor is a true ancestor (its UUIDs contain new candidate's UUIDs)
                if (ancestor.AllUuids.IsSupersetOf(newCandidate.AllUuids)
                    && ancestor.AllUuids.Count > newCandidate.AllUuids.Count)
                {
                    // Ancestor/descendant conflict detected
                    if (newCandidate.Locations.Count >= MinIndependentLocations
                        || newCandidate.Locations.Count >= ancestor.Locations.Count * ChildLocationRatio)
                    {
                        // New candidate is more granular and has enough locations → prefer new, remove ancestor
                        ancestorsToRemove.Add(ancestor);
                    }
                    else
                    {
                        // Ancestor is better → don't add new candidate
                        shouldAddNewCandidate = false;
                        break;
                    }
                }
            }

            // Remove conflicting ancestors
            foreach (var ancestor in ancestorsToRemove)
            {
                candidates.Remove(ancestor);
                ancestorStack.Remove(ancestor);
            }

            if (shouldAddNewCandidate)
            {
                candidates.Add(newCandidate);
                ancestorStack.Add(newCandidate);
            }
        }

        // Recurse into children
        foreach (var child in node.Children)
        {
            WalkPopoTree(child, uuidToFeature, candidates, ancestorStack, ref order, depth + 1, cancellationToken);
        }

        // Backtrack: remove this node from the ancestor list if we added it
        if (ancestorStack.Count > 0 && ancestorStack[ancestorStack.Count - 1].TreeNode == node)
        {
            ancestorStack.RemoveAt(ancestorStack.Count - 1);
        }
    }

    /// <summary>
    /// Recursively collects all source_block_ids from a node and its descendants.
    /// </summary>
    static HashSet<string> CollectAllSourceBlockIds(AnalysisTreeNode node, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var ids = new HashSet<string>(node.SourceBlockIds ?? Enumerable.Empty<string>());
        if (node.Children is not null)
        {
            foreach (var child in node.Children)
            {
                ids.UnionWith(CollectAllSourceBlockIds(child, cancellationToken));
            }
        }
        return ids;
    }

    /// <summary>
    /// Analyzes all chapter candidates to compute per-depth camera ranges.
    /// </summary>
    static List<DepthCameraRange> AnalyzeDepthRanges(
        List<ChapterCandidate> candidates,
        CancellationToken cancellationToken = default)
    {
        var depthGroups = candidates.GroupBy(c => c.Depth).ToList();
        var ranges = new List<DepthCameraRange>();

        foreach (var group in depthGroups)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var depth = group.Key;
            var zooms = new List<double>();
            var pitches = new List<double>();

            foreach (var candidate in group)
            {
                var (zoom, pitch) = EstimateCameraForCandidate(candidate);
                zooms.Add(zoom);
                pitches.Add(pitch);
            }

            if (zooms.Count == 0)
                continue;

            var sortedZooms = zooms.OrderBy(z => z).ToList();
            var sortedPitches = pitches.OrderBy(p => p).ToList();

            ranges.Add(new DepthCameraRange
            {
                Depth = depth,
                MinZoom = sortedZooms.First(),
                MaxZoom = sortedZooms.Last(),
                TypicalZoom = sortedZooms[sortedZooms.Count / 2],
                MinPitch = sortedPitches.First(),
                MaxPitch = sortedPitches.Last(),
                TypicalPitch = sortedPitches[sortedPitches.Count / 2]
            });
        }

        return ranges;
    }

    /// <summary>
    /// Estimates raw zoom/pitch for a candidate (used during analysis phase).
    /// </summary>
    static (double Zoom, double Pitch) EstimateCameraForCandidate(ChapterCandidate candidate)
    {
        var locs = candidate.Locations;
        if (locs.Count == 0)
            return (12, 0);

        var rolePriority = new Dictionary<string, int>
        {
            { "PATH", 6 }, { "TARGET", 5 }, { "ORIGIN", 4 },
            { "ACTOR", 3 }, { "CONTAINER", 2 }, { "MODIFIER", 1 }
        };

        var dominantRole = locs
            .Where(l => !string.IsNullOrEmpty(l.SpatialRole))
            .OrderByDescending(l => rolePriority.GetValueOrDefault(l.SpatialRole!, 0))
            .Select(l => l.SpatialRole)
            .FirstOrDefault() ?? "STATIC";

        double baseZoom;
        if (locs.Count == 1)
        {
            baseZoom = GetZoomFromPlaceRank(locs[0].PlaceRank);
        }
        else
        {
            var lonSpan = locs.Max(l => l.Longitude) - locs.Min(l => l.Longitude);
            var latSpan = locs.Max(l => l.Latitude) - locs.Min(l => l.Latitude);
            var maxSpan = Math.Max(lonSpan, latSpan);
            baseZoom = maxSpan < 0.0001
                ? GetZoomFromPlaceRank(locs[0].PlaceRank)
                : Math.Log(360.0 / maxSpan) / Math.Log(2.0) - 0.5;
            baseZoom = Math.Max(1.0, Math.Min(20.0, baseZoom));
        }

        double zoom = baseZoom;
        double pitch = 0;

        switch (dominantRole)
        {
            case "PATH": pitch = 35; break;
            case "TARGET": zoom = Math.Min(baseZoom + 2, 18); break;
            case "ACTOR": zoom = Math.Min(baseZoom + 1, 18); pitch = 20; break;
            case "CONTAINER": pitch = 10; break;
            case "MODIFIER": zoom = Math.Max(baseZoom - 1, 2); break;
        }

        return (zoom, pitch);
    }

    /// <summary>
    /// Constrains camera params to depth range and smooths transitions from previous chapter.
    /// </summary>
    static (double Zoom, double Pitch) ConstrainCameraToRange(
        double rawZoom, double rawPitch,
        DepthCameraRange range,
        GeoChapter? previousChapter)
    {
        // Step 1: Clamp to depth range (with 1-level tolerance)
        double zoom = Math.Max(range.MinZoom - 1, Math.Min(range.MaxZoom + 1, rawZoom));
        double pitch = Math.Max(range.MinPitch, Math.Min(range.MaxPitch, rawPitch));

        // Step 2: Smooth transition from previous chapter
        if (previousChapter is not null)
        {
            const double MaxZoomDelta = 3.0;
            const double MaxPitchDelta = 15.0;

            var zoomDelta = zoom - previousChapter.Zoom;
            if (Math.Abs(zoomDelta) > MaxZoomDelta)
                zoom = previousChapter.Zoom + Math.Sign(zoomDelta) * MaxZoomDelta;

            var pitchDelta = pitch - previousChapter.Pitch;
            if (Math.Abs(pitchDelta) > MaxPitchDelta)
                pitch = previousChapter.Pitch + Math.Sign(pitchDelta) * MaxPitchDelta;
        }

        zoom = Math.Max(1.0, Math.Min(20.0, zoom));
        pitch = Math.Max(0.0, Math.Min(60.0, pitch));

        return (zoom, pitch);
    }

    /// <summary>
    /// Builds a single GeoChapter from a validated candidate.
    /// Camera behavior adapts to spatial_role and verb_spatial_class.
    /// Camera parameters are constrained by depth-based ranges and smoothed across transitions.
    /// </summary>
    static GeoChapter BuildChapter(
        ChapterCandidate candidate, int index,
        List<DepthCameraRange> depthRanges,
        GeoChapter? previousChapter,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var locs = candidate.Locations;
        var (lng, lat, rawZoom, rawPitch, bearing, mapAnimation) = CalculateSpatialCamera(locs);

        // Find the depth range for this candidate's depth
        var range = depthRanges.FirstOrDefault(r => r.Depth == candidate.Depth);

        // If no range found for this depth, create a default range based on raw values
        if (range.Depth == 0)
        {
            range = new DepthCameraRange
            {
                Depth = candidate.Depth,
                MinZoom = Math.Max(1, rawZoom - 2),
                MaxZoom = Math.Min(20, rawZoom + 2),
                TypicalZoom = rawZoom,
                MinPitch = 0,
                MaxPitch = 60,
                TypicalPitch = rawPitch
            };
        }

        // Apply depth-based constraints and smooth transitions
        var (zoom, pitch) = ConstrainCameraToRange(rawZoom, rawPitch, range, previousChapter);

        System.Diagnostics.Debug.WriteLine(
            $"[GeoStoryBuilder] Chapter {index} (depth={candidate.Depth}): " +
            $"raw zoom={rawZoom:F1} pitch={rawPitch:F1} → constrained zoom={zoom:F1} pitch={pitch:F1}");

        // Determine which layers are "active" in this chapter
        var activeLayerIds = locs
            .Select(l => RoleToLayerId(l.SyntacticRole))
            .Distinct()
            .ToHashSet();

        // Description: use the first location's source text, truncated
        var description = locs.FirstOrDefault()?.SourceBlockContent ?? "";
        if (description.Length > 200)
            description = description.Substring(0, 200) + "...";

        return new GeoChapter
        {
            Id = $"chapter-{index}",
            Title = candidate.Title,
            Description = description,
            Alignment = index % 2 == 0 ? "right" : "left",
            MapAnimation = mapAnimation,
            Lng = lng,
            Lat = lat,
            Zoom = zoom,
            Pitch = pitch,
            Bearing = bearing,
            OnChapterEnter = AllLayerIds.Select(id => new GeoLayerEffect
            {
                LayerId = id,
                Opacity = activeLayerIds.Contains(id) ? 1.0 : 0.2,
                Duration = 500
            }).ToList(),
            OnChapterExit = AllLayerIds.Select(id => new GeoLayerEffect
            {
                LayerId = id,
                Opacity = 0.7,
                Duration = 300
            }).ToList(),
            Beats = BuildBeats(locs)
        };
    }

    /// <summary>
    /// Backward-compatible overload (no constraints).
    /// </summary>
    static GeoChapter BuildChapter(ChapterCandidate candidate, int index)
    {
        return BuildChapter(candidate, index, new List<DepthCameraRange>(), null, CancellationToken.None);
    }

    /// <summary>
    /// Phase 2: Global camera parameter optimization.
    /// After all chapters are built, performs a global pass to smooth zoom/pitch transitions
    /// from an overall balanced perspective.
    /// 
    /// Strategy:
    /// 1. Normalize zoom values to a reasonable global range (3-15)
    /// 2. Apply exponential moving average smoothing to reduce abrupt changes
    /// 3. Enforce max delta constraints between adjacent chapters
    /// 4. Preserve semantic hierarchy (depth-based relative ordering)
    /// </summary>
    static void OptimizeGlobalCameraParameters(List<GeoChapter> chapters)
    {
        if (chapters.Count < 2)
            return;

        // Step 1: Collect all zoom values to understand the distribution
        var zooms = chapters.Select(c => c.Zoom).ToList();
        var minZoom = zooms.Min();
        var maxZoom = zooms.Max();
        var zoomRange = maxZoom - minZoom;

        System.Diagnostics.Debug.WriteLine(
            $"[GeoStoryBuilder] Global optimization: {chapters.Count} chapters, " +
            $"zoom range [{minZoom:F1}, {maxZoom:F1}], span={zoomRange:F1}");

        // Step 2: Normalize zoom to target range [3, 15] while preserving relative ordering
        const double TargetMinZoom = 3.0;
        const double TargetMaxZoom = 15.0;
        const double TargetRange = TargetMaxZoom - TargetMinZoom;

        foreach (var chapter in chapters)
        {
            if (zoomRange < 0.01) // All chapters have same zoom, use default
            {
                chapter.Zoom = 8.0; // Medium zoom as default
            }
            else
            {
                // Linear normalization to target range
                var normalizedZoom = TargetMinZoom + (chapter.Zoom - minZoom) / zoomRange * TargetRange;
                chapter.Zoom = normalizedZoom;
            }
        }

        // Step 3: Apply exponential moving average smoothing (alpha = 0.4)
        // This reduces abrupt changes while preserving overall trend
        const double smoothingAlpha = 0.4;
        var smoothedZooms = new double[chapters.Count];
        smoothedZooms[0] = chapters[0].Zoom;

        for (int i = 1; i < chapters.Count; i++)
        {
            smoothedZooms[i] = smoothingAlpha * chapters[i].Zoom + (1 - smoothingAlpha) * smoothedZooms[i - 1];
        }

        // Apply smoothed values
        for (int i = 0; i < chapters.Count; i++)
        {
            chapters[i].Zoom = smoothedZooms[i];
        }

        // Step 4: Enforce max delta constraint between adjacent chapters (max 3 zoom levels)
        const double maxZoomDelta = 3.0;
        for (int i = 1; i < chapters.Count; i++)
        {
            var delta = chapters[i].Zoom - chapters[i - 1].Zoom;
            if (Math.Abs(delta) > maxZoomDelta)
            {
                // Interpolate to stay within constraint
                chapters[i].Zoom = chapters[i - 1].Zoom + Math.Sign(delta) * maxZoomDelta;
            }
        }

        // Step 5: Smooth pitch values (similar approach)
        const double maxPitchDelta = 10.0;
        for (int i = 1; i < chapters.Count; i++)
        {
            var pitchDelta = chapters[i].Pitch - chapters[i - 1].Pitch;
            if (Math.Abs(pitchDelta) > maxPitchDelta)
            {
                chapters[i].Pitch = chapters[i - 1].Pitch + Math.Sign(pitchDelta) * maxPitchDelta;
            }
        }

        // Step 6: Final safety bounds
        foreach (var chapter in chapters)
        {
            chapter.Zoom = Math.Max(1.0, Math.Min(20.0, chapter.Zoom));
            chapter.Pitch = Math.Max(0.0, Math.Min(60.0, chapter.Pitch));
        }

        // Log results
        var finalZooms = chapters.Select(c => c.Zoom).ToList();
        System.Diagnostics.Debug.WriteLine(
            $"[GeoStoryBuilder] After optimization: zoom range [{finalZooms.Min():F1}, {finalZooms.Max():F1}]");
    }

    /// <summary>
    /// Generates transition chapters between two chapters when there's a large spatial or zoom jump.
    /// This ensures smooth camera transitions by interpolating center, zoom, and pitch.
    /// 
    /// Thresholds:
    /// - Zoom delta > 5 levels: generate transitions
    /// - Distance > 500km: generate transitions
    /// 
    /// Each transition chapter is marked as Hidden=true (map-only, no text panel).
    /// </summary>
    static List<GeoChapter> GenerateTransitionChapters(
        GeoChapter from, GeoChapter to, int transitionStartIndex)
    {
        var transitions = new List<GeoChapter>();

        // Calculate zoom and distance deltas
        var zoomDelta = Math.Abs(to.Zoom - from.Zoom);
        var distanceKm = CalculateGreatCircleDistance(from.Lng, from.Lat, to.Lng, to.Lat);

        // Determine if transitions are needed
        bool needsTransition = zoomDelta > 5 || distanceKm > 500;
        if (!needsTransition)
            return transitions;

        // Calculate number of transition steps (1-3 based on severity)
        int numSteps;
        if (zoomDelta > 10 || distanceKm > 1500)
            numSteps = 3;
        else if (zoomDelta > 7 || distanceKm > 800)
            numSteps = 2;
        else
            numSteps = 1;

        // Generate intermediate chapters
        for (int i = 1; i <= numSteps; i++)
        {
            var t = (double)i / (numSteps + 1); // Interpolation factor (0 to 1)

            // Spherical interpolation for center point (along great circle)
            var (lng, lat) = SphericalInterpolate(from.Lng, from.Lat, to.Lng, to.Lat, t);

            // Linear interpolation for zoom and pitch
            var zoom = from.Zoom + (to.Zoom - from.Zoom) * t;
            var pitch = from.Pitch + (to.Pitch - from.Pitch) * t;
            var bearing = from.Bearing + (to.Bearing - from.Bearing) * t;

            // Create transition chapter
            var transition = new GeoChapter
            {
                Id = $"transition-{transitionStartIndex}-{i}",
                Title = $"{from.Title} → {to.Title}",
                Description = "",
                Image = "",
                Alignment = "full",
                Hidden = true, // Hide text panel, show only map animation
                MapAnimation = "flyTo",
                Lng = lng,
                Lat = lat,
                Zoom = zoom,
                Pitch = pitch,
                Bearing = bearing,
                RotateAnimation = false,
                OnChapterEnter = AllLayerIds.Select(id => new GeoLayerEffect
                {
                    LayerId = id,
                    Opacity = 0.5, // Dim all layers during transition
                    Duration = 300
                }).ToList(),
                OnChapterExit = Array.Empty<GeoLayerEffect>().ToList(),
                Beats = new List<GeoBeat>()
            };

            transitions.Add(transition);
            System.Diagnostics.Debug.WriteLine(
                $"[GeoStoryBuilder] Transition {i}/{numSteps}: zoom={zoom:F1} center=({lng:F2}, {lat:F2})");
        }

        return transitions;
    }

    /// <summary>
    /// Calculates the great circle distance between two points in kilometers.
    /// Uses the Haversine formula.
    /// </summary>
    static double CalculateGreatCircleDistance(double lng1, double lat1, double lng2, double lat2)
    {
        const double EarthRadiusKm = 6371.0;
        var dLat = ToRadians(lat2 - lat1);
        var dLng = ToRadians(lng2 - lng1);
        var a = Math.Sin(dLat / 2) * Math.Sin(dLat / 2)
              + Math.Cos(ToRadians(lat1)) * Math.Cos(ToRadians(lat2))
              * Math.Sin(dLng / 2) * Math.Sin(dLng / 2);
        var c = 2 * Math.Atan2(Math.Sqrt(a), Math.Sqrt(1 - a));
        return EarthRadiusKm * c;
    }

    /// <summary>
    /// Performs spherical interpolation (great circle) between two points.
    /// Returns the interpolated longitude and latitude at factor t (0 to 1).
    /// </summary>
    static (double Lng, double Lat) SphericalInterpolate(
        double lng1, double lat1, double lng2, double lat2, double t)
    {
        var phi1 = ToRadians(lat1);
        var phi2 = ToRadians(lat2);
        var lambda1 = ToRadians(lng1);
        var lambda2 = ToRadians(lng2);

        // Great circle interpolation using spherical linear interpolation (slerp)
        var d = 2.0 * Math.Asin(Math.Sqrt(
            Math.Sin((phi2 - phi1) / 2.0) * Math.Sin((phi2 - phi1) / 2.0) +
            Math.Cos(phi1) * Math.Cos(phi2) *
            Math.Sin((lambda2 - lambda1) / 2.0) * Math.Sin((lambda2 - lambda1) / 2.0)));

        if (d < 1e-6) // Points are essentially the same
            return (lng1, lat1);

        var a = Math.Sin((1.0 - t) * d) / Math.Sin(d);
        var b = Math.Sin(t * d) / Math.Sin(d);

        // Convert to Cartesian, interpolate, convert back
        var x = a * Math.Cos(phi1) * Math.Cos(lambda1) + b * Math.Cos(phi2) * Math.Cos(lambda2);
        var y = a * Math.Cos(phi1) * Math.Sin(lambda1) + b * Math.Cos(phi2) * Math.Sin(lambda2);
        var z = a * Math.Sin(phi1) + b * Math.Sin(phi2);

        var lat = Math.Atan2(z, Math.Sqrt(x * x + y * y));
        var lng = Math.Atan2(y, x);

        return (ToDegrees(lng), ToDegrees(lat));
    }

    static double ToRadians(double degrees) => degrees * Math.PI / 180.0;
    static double ToDegrees(double radians) => radians * 180.0 / Math.PI;

    /// <summary>
    /// Builds narrative beats from locations that have meaningful spatial roles.
    /// Excludes MODIFIER and STATIC — only dynamic spatial roles generate beats.
    /// </summary>
    static List<GeoBeat> BuildBeats(List<GeoFeature> locations)
    {
        var beatRoles = new HashSet<string> { "CONTAINER", "TARGET", "ORIGIN", "PATH", "ACTOR" };

        return locations
            .Where(l => !string.IsNullOrEmpty(l.SpatialRole)
                     && beatRoles.Contains(l.SpatialRole))
            .Select(l => new GeoBeat
            {
                LocationName = l.Name,
                SpatialRole = l.SpatialRole!,
                Verb = l.VerbSpatialClass ?? "",
                Lng = l.Longitude,
                Lat = l.Latitude,
                // Use place_rank as base zoom, then adjust by spatial role
                Zoom = Math.Clamp(
                    GetZoomFromPlaceRank(l.PlaceRank)
                    + (l.SpatialRole == "TARGET" ? 2 : 0)
                    + (l.SpatialRole == "ACTOR" ? 1 : 0),
                    3, 20),
                Pitch = l.SpatialRole switch
                {
                    "PATH" => 35,
                    "ACTOR" => 20,
                    "CONTAINER" => 10,
                    _ => 0
                },
                Bearing = 0
            })
            .ToList();
    }

    /// <summary>
    /// Calculates camera position, zoom, pitch, bearing, and animation type
    /// based on the spatial roles and verb spatial classes of the chapter's locations.
    /// </summary>
    static (double Lng, double Lat, double Zoom, double Pitch, double Bearing, string MapAnimation)
        CalculateSpatialCamera(List<GeoFeature> locations)
    {
        if (locations.Count == 0)
            return (0, 0, 3, 0, 0, "flyTo");

        // Determine the dominant spatial role (highest priority first)
        var rolePriority = new Dictionary<string, int>
        {
            { "PATH", 6 }, { "TARGET", 5 }, { "ORIGIN", 4 },
            { "ACTOR", 3 }, { "CONTAINER", 2 }, { "MODIFIER", 1 }
        };

        var dominantRole = locations
            .Where(l => !string.IsNullOrEmpty(l.SpatialRole))
            .OrderByDescending(l => rolePriority.GetValueOrDefault(l.SpatialRole!, 0))
            .Select(l => l.SpatialRole)
            .FirstOrDefault() ?? "STATIC";

        // Base camera from bounding box
        var (centerLng, centerLat, baseZoom) = ComputeBaseCamera(locations);

        // Apply spatial role adjustments
        double zoom = baseZoom;
        double pitch = 0;
        double bearing = 0;
        string mapAnimation = "flyTo";

        switch (dominantRole)
        {
            case "PATH":
                zoom = baseZoom;
                pitch = 35;
                bearing = ComputePathBearing(locations);
                mapAnimation = "flyTo";
                break;

            case "TARGET":
                zoom = Math.Min(baseZoom + 2, 18);
                pitch = 0;
                mapAnimation = "easeTo";
                break;

            case "ORIGIN":
                zoom = baseZoom;
                pitch = 0;
                mapAnimation = "flyTo";
                break;

            case "ACTOR":
                zoom = Math.Min(baseZoom + 1, 18);
                pitch = 20;
                mapAnimation = "flyTo";
                break;

            case "CONTAINER":
                zoom = baseZoom;
                pitch = 10;
                mapAnimation = "flyTo";
                break;

            case "MODIFIER":
                zoom = Math.Max(baseZoom - 1, 2);
                pitch = 0;
                mapAnimation = "flyTo";
                break;

            default: // STATIC or unknown
                zoom = baseZoom;
                pitch = 0;
                mapAnimation = "flyTo";
                break;
        }

        // Verb class overrides for animation type
        var dominantVerbClass = locations
            .Where(l => !string.IsNullOrEmpty(l.VerbSpatialClass))
            .Select(l => l.VerbSpatialClass)
            .FirstOrDefault();

        if (dominantVerbClass == "MOVE_TO")
            mapAnimation = "easeTo";
        else if (dominantVerbClass == "VIEW")
            pitch = Math.Max(pitch, 15);

        return (centerLng, centerLat, zoom, pitch, bearing, mapAnimation);
    }

    /// <summary>
    /// Computes base camera from bounding box of all locations.
    /// </summary>
    static (double Lng, double Lat, double Zoom) ComputeBaseCamera(List<GeoFeature> locations)
    {
        if (locations.Count == 1)
        {
            var loc = locations[0];
            // Use place_rank to determine appropriate zoom level
            double locZoom = GetZoomFromPlaceRank(loc.PlaceRank);
            return (loc.Longitude, loc.Latitude, locZoom);
        }

        var lngs = locations.Select(l => l.Longitude).ToList();
        var lats = locations.Select(l => l.Latitude).ToList();
        var centerLng = (lngs.Min() + lngs.Max()) / 2;
        var centerLat = (lats.Min() + lats.Max()) / 2;

        var lonSpan = lngs.Max() - lngs.Min();
        var latSpan = lats.Max() - lats.Min();
        var maxSpan = Math.Max(lonSpan, latSpan);

        if (maxSpan < 0.0001)
        {
            // All points are the same, use place_rank of the first location
            double rankZoom = GetZoomFromPlaceRank(locations[0].PlaceRank);
            return (centerLng, centerLat, rankZoom);
        }

        var zoom = Math.Log(360.0 / maxSpan) / Math.Log(2.0) - 0.5;
        zoom = Math.Max(1.0, Math.Min(20.0, zoom));

        return (centerLng, centerLat, zoom);
    }

    /// <summary>
    /// Converts Nominatim place_rank to an appropriate map zoom level.
    /// place_rank ranges: 3-4=国家, 5-9=省/州, 10-12=县, 13-16=城市, 17-21=区/镇, 22-24=社区, 25-27=街道, 28+=建筑
    /// </summary>
    static double GetZoomFromPlaceRank(int placeRank)
    {
        if (placeRank <= 0)
            return 12; // Default zoom when place_rank is not available

        return placeRank switch
        {
            <= 2  => 3,    // Continent/Sea
            <= 4  => 5,    // Country
            <= 6  => 7,    // State/province (high level)
            <= 9  => 8,    // State/province
            <= 12 => 10,   // County
            <= 16 => 12,   // City
            <= 21 => 14,   // District/town
            <= 24 => 16,   // Locality/community
            <= 27 => 17,   // Street
            _     => 18    // Building/house
        };
    }

    /// <summary>
    /// Computes bearing angle from PATH-type locations' OSM bounding boxes.
    /// Falls back to 0 (north-up) if no bbox data is available.
    /// </summary>
    static double ComputePathBearing(List<GeoFeature> locations)
    {
        var pathLocs = locations
            .Where(l => l.SpatialRole == "PATH" && l.BboxMinLat.HasValue)
            .ToList();

        if (pathLocs.Count == 0)
            pathLocs = locations.Where(l => l.BboxMinLat.HasValue).ToList();

        if (pathLocs.Count == 0)
            return 0;

        // Use the first location with bbox data to determine path direction
        var loc = pathLocs[0];
        var dLon = (loc.BboxMaxLon!.Value - loc.BboxMinLon!.Value);
        var dLat = (loc.BboxMaxLat!.Value - loc.BboxMinLat!.Value);

        // atan2(dLon, dLat) → radians → degrees, normalized to [0, 360)
        var bearingRad = Math.Atan2(dLon, dLat);
        var bearingDeg = bearingRad * 180.0 / Math.PI;
        if (bearingDeg < 0) bearingDeg += 360;

        return bearingDeg;
    }

    /// <summary>
    /// Maps a syntactic role string to the corresponding GeoLibre layer ID.
    /// </summary>
    static string RoleToLayerId(string role) => role switch
    {
        "Adverbial" => "layer-adverbial",
        "Subject" => "layer-subject",
        "Object" => "layer-object",
        "Attributive" => "layer-attributive",
        "Predicative" => "layer-predicative",
        _ => "layer-unknown"
    };

    /// <summary>
    /// Converts a GeoStoryConfig tree to Dictionary<string, object> for
    /// AOT-safe JSON serialization via GeoJsonService.BuildJson().
    /// Uses GeoLibre 0.2.0 format with nested "location" object per chapter.
    /// </summary>
    public static Dictionary<string, object>? GeoStoryConfigToDict(GeoStoryConfig? config)
    {
        if (config is null)
            return null;

        var dict = new Dictionary<string, object>
        {
            { "title", config.Title },
            { "subtitle", config.Subtitle },
            { "byline", config.Byline },
            { "footer", config.Footer },
            { "theme", config.Theme },
            { "showMarkers", config.ShowMarkers },
            { "markerColor", config.MarkerColor },
            { "inset", config.Inset },
            { "insetPosition", config.InsetPosition },
            { "hideChapterNav", config.HideChapterNav },
            { "startSlide", config.StartSlide },
            { "endSlide", config.EndSlide }
        };

        if (config.Chapters.Count > 0)
        {
            var chapterDicts = new List<Dictionary<string, object>>();
            foreach (var ch in config.Chapters)
            {
                chapterDicts.Add(ChapterToDict(ch));
            }
            dict["chapters"] = chapterDicts;
        }
        else
        {
            dict["chapters"] = Array.Empty<object>();
        }

        return dict;
    }

    static Dictionary<string, object> ChapterToDict(GeoChapter chapter)
    {
        // GeoLibre 0.2.0 uses a nested "location" object for camera parameters
        var location = new Dictionary<string, object>
        {
            { "center", new[] { chapter.Lng, chapter.Lat } },
            { "zoom", chapter.Zoom },
            { "pitch", chapter.Pitch },
            { "bearing", chapter.Bearing }
        };

        var dict = new Dictionary<string, object>
        {
            { "id", chapter.Id },
            { "title", chapter.Title },
            { "description", chapter.Description },
            { "image", chapter.Image },
            { "alignment", chapter.Alignment },
            { "hidden", chapter.Hidden },
            { "location", location },
            { "mapAnimation", chapter.MapAnimation },
            { "rotateAnimation", chapter.RotateAnimation }
        };

        if (chapter.OnChapterEnter.Count > 0)
            dict["onChapterEnter"] = LayerEffectsToArray(chapter.OnChapterEnter);
        else
            dict["onChapterEnter"] = Array.Empty<object>();

        if (chapter.OnChapterExit.Count > 0)
            dict["onChapterExit"] = LayerEffectsToArray(chapter.OnChapterExit);
        else
            dict["onChapterExit"] = Array.Empty<object>();

        if (chapter.Beats.Count > 0)
            dict["beats"] = BeatsToArray(chapter.Beats);
        else
            dict["beats"] = Array.Empty<object>();

        return dict;
    }

    static object[] LayerEffectsToArray(List<GeoLayerEffect> effects)
    {
        return effects.Select(e => (object)new Dictionary<string, object>
        {
            { "layerId", e.LayerId },
            { "opacity", e.Opacity },
            { "duration", e.Duration }
        }).ToArray();
    }

    static object[] BeatsToArray(List<GeoBeat> beats)
    {
        return beats.Select(b => (object)new Dictionary<string, object>
        {
            { "locationName", b.LocationName },
            { "spatialRole", b.SpatialRole },
            { "verb", b.Verb },
            { "lng", b.Lng },
            { "lat", b.Lat },
            { "zoom", b.Zoom },
            { "pitch", b.Pitch },
            { "bearing", b.Bearing }
        }).ToArray();
    }
